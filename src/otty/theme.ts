/**
 * Otty Terminal Theme Generator
 * Generates .ottytheme TOML files for Otty terminal
 * Spec: https://docs.otty.sh/reference/theme-format
 * Chrome shape follows Otty's Nord reference theme (docs/spec/THEME_SPEC.md).
 */

import type { Semantic } from "../palette";

const AUTHOR = "kumamaki";
const DESCRIPTION =
	"Minimalistic dark theme with playful coral accents";

/** `#RRGGBB` → `rgba(r,g,b,a)` for Otty hover/active fills */
function hexToRgba(hex: string, alpha: number): string {
	const normalized = hex.replace("#", "").slice(0, 6);
	const r = Number.parseInt(normalized.slice(0, 2), 16);
	const g = Number.parseInt(normalized.slice(2, 4), 16);
	const b = Number.parseInt(normalized.slice(4, 6), 16);
	return `rgba(${r},${g},${b},${alpha})`;
}

/**
 * Creates an Otty .ottytheme TOML string from semantic palette
 *
 * Sections:
 * - [meta] / [terminal] — required identity + ANSI
 * - [selection] / [cursor] / [ghost] — terminal interaction
 * - [token] / [panel] / [window] / [titlebar] / [sidebar] / [tab] /
 *   [tab-bar] / [container] / [divider] — rich window chrome
 */
export function createOttyTheme(semantic: Semantic, name: string): string {
	const hoverBg = "rgba(255,255,255,0.05)";
	const activeBg = hexToRgba(semantic.badgeBackground, 0.18);
	const panelBorder = hexToRgba(semantic.panelBorder, 0.35);
	const divider = hexToRgba(semantic.sidebarBorder, 0.55);

	return `# Generated by Short Giraffe — do not edit by hand
# Source: src/otty/theme.ts + src/palette.ts

[meta]
name        = "${name}"
author      = "${AUTHOR}"
mode        = "dark"
description = "${DESCRIPTION}"

[terminal]
foreground           = "${semantic.terminalForeground}"
background           = "${semantic.terminalBackground}"
cursor               = "${semantic.editorCursor}"
cursor-text          = "${semantic.terminalBackground}"
selection-foreground = "${semantic.editorForeground}"
selection-background = "${semantic.editorSelection}"
palette = [
  "${semantic.terminalBlack}", "${semantic.terminalRed}", "${semantic.terminalGreen}", "${semantic.terminalYellow}",
  "${semantic.terminalBlue}", "${semantic.terminalMagenta}", "${semantic.terminalCyan}", "${semantic.terminalWhite}",
  "${semantic.terminalBrightBlack}", "${semantic.terminalBrightRed}", "${semantic.terminalBrightGreen}", "${semantic.terminalBrightYellow}",
  "${semantic.terminalBrightBlue}", "${semantic.terminalBrightMagenta}", "${semantic.terminalBrightCyan}", "${semantic.terminalBrightWhite}",
]

[selection]
foreground = "${semantic.editorForeground}"
background = "${semantic.editorSelection}"

[cursor]
color = "${semantic.editorCursor}"
text  = "${semantic.terminalBackground}"

[ghost]
foreground = "${semantic.terminalBrightBlack}"

[token]
foreground = "${semantic.terminalForeground}"
secondary  = "${semantic.sidebarForeground}"
tertiary   = "${semantic.tabInactiveForeground}"
accent     = "${semantic.badgeBackground}"
success    = "${semantic.terminalGreen}"
warning    = "${semantic.terminalYellow}"
danger     = "${semantic.terminalRed}"
hover-bg   = "${hoverBg}"
active-bg  = "${activeBg}"
radius     = 6
shadow     = "0 8px 24px rgba(0,0,0,0.35)"
font-ui    = ["-apple-system", "BlinkMacSystemFont", "SF Pro", "sans-serif"]
font-mono  = ["JetBrains Mono", "SF Mono", "Menlo", "monospace"]
font-size  = 13

[panel]
background = "${semantic.sidebarBackground}"
surface    = "${semantic.tabActiveBackground}"
border     = "${panelBorder}"

[window]
background = "${semantic.terminalBackground}"
material   = "none"
radius     = 12

[window.unfocused]
opacity = 0.92

[titlebar]
foreground  = "${semantic.titleBarActiveForeground}"
font-size   = 13
font-weight = 500
height      = 40

[titlebar.unfocused]
foreground = "${semantic.titleBarInactiveForeground}"

[sidebar]
background   = "${semantic.sidebarBackground}"
border-right = "1px solid ${semantic.sidebarBorder}"
width        = 220
material     = "none"

[tab]
background  = "transparent"
foreground  = "${semantic.tabInactiveForeground}"
radius      = 6
font-size   = 13
font-weight = 400
padding     = 10
indicator-color = "${semantic.tabInactiveForeground}"

[tab.hover]
background = "${hoverBg}"

[tab.active]
background  = "${semantic.tabActiveBackground}"
foreground  = "${semantic.tabActiveForeground}"
font-weight = 500
shadow      = "0 1px 2px rgba(0,0,0,0.25)"
indicator-color = "${semantic.badgeBackground}"

[tab.active.unfocused]
background = "${semantic.tabActiveBackground}"
foreground = "${semantic.tabInactiveForeground}"
shadow     = "none"

[tab-bar]
height        = 36
padding       = 8
border-bottom = "1px solid ${panelBorder}"

[tab-bar.tab]
radius = 8
height = 28

[container]
background = "${semantic.terminalBackground}"
radius     = 0
margin     = 0
padding    = 8

[divider]
color = "${divider}"
width = 1
`;
}
